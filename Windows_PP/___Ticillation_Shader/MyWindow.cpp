GLuint TicillationControlShaderObject;
GLuint TicillationEvaluationShaderObject;

GLuint vao;
GLuint vbo_Position;
GLuint vbo_Color;
GLuint mvpUniform;

GLuint numberOfSegmentsUniform;
GLuint numberOfStripsUniform;
GLuint lineColorUniform;

